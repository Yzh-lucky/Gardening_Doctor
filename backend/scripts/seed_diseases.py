def _normalize(raw: dict) -> dict:
    """校验并归一化一条种子数据；结构不对直接抛错，不把脏数据写进知识库。"""
    data = dict(raw)

    name = str(data.get("name") or "").strip()
    if not name:
        raise ValueError("种子数据存在空的 name")

    for field, limit in _MAX_LEN.items():
        value = data.get(field)
        if value is not None and len(str(value)) > limit:
            raise ValueError(f"{name}: 字段 {field} 超过 {limit} 字符上限")

    # plan_* 用与接口一致的模型校验并归一化，落库形状和 admin CRUD 完全相同：
    # degrade 会拿这些 dict 直接构造 Plan 模型，形状不对会在降级时抛异常
    for field, model in (("plan_l1", PlanL1), ("plan_l2", PlanL2), ("plan_l3", PlanL3)):
        value = data.get(field)
        if value is None:
            continue
        data[field] = model.model_validate(value).model_dump(mode="json")

    return data


def seed_diseases(entries: list[dict]) -> tuple[int, int, int]:
    """按病名幂等导入。返回（新增数, 更新数, 跳过数）。

    内容没变就跳过：版本号只在种子清单真的改动时自增（与 admin 修改接口一致），
    避免反复执行把 version 刷出一堆虚假的"内容变更"记录。
    """
    created = updated = skipped = 0
    with SessionLocal() as db:
        for raw in entries:
            data = _normalize(raw)
            row = db.scalar(select(Disease).where(Disease.name == data["name"]))
            if row is None:
                db.add(Disease(**data, version=1))
                created += 1
                continue

            changed = {field: value for field, value in data.items() if getattr(row, field) != value}
            if changed:
                for field, value in changed.items():
                    setattr(row, field, value)
                row.version = int(row.version or 1) + 1
                updated += 1
            else:
                skipped += 1
        db.commit()
    return created, updated, skipped


def main() -> None:
    parser = argparse.ArgumentParser(description="导入常见病虫害种子数据到知识库（幂等）")
    parser.add_argument("--dry-run", action="store_true", help="只校验数据形状，不写库")
    args = parser.parse_args()

    if args.dry_run:
        for raw in SEED_DISEASES:
            _normalize(raw)
        print(f"[seed_diseases] dry-run: {len(SEED_DISEASES)} 条数据校验通过，未写库")
        return

    created, updated, skipped = seed_diseases(SEED_DISEASES)
    print(
        f"[seed_diseases] 完成：新增 {created} 条，更新 {updated} 条，"
        f"跳过 {skipped} 条（内容未变），共 {len(SEED_DISEASES)} 条"
    )


if __name__ == "__main__":
    main()
